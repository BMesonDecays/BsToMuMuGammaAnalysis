//object definition
class countEvents : public edm::one::EDAnalyzer<> {
public:

  //constructor, function is called when new object is created
  explicit countEvents(const edm::ParameterSet& conf);

  //destructor, function is called when object is destroyed
  ~countEvents();

  //edm filter plugin specific functions
  virtual void beginJob();
  virtual void analyze(const edm::Event&, const edm::EventSetup&);
  virtual void endJob();

private:

  edm::ParameterSet theConfig;
  unsigned int theEventCount;

  TNtupleD* tevCount;
    
};


countEvents::countEvents(const edm::ParameterSet& conf)
  : theConfig(conf), theEventCount(0)
{
  cout <<" CTORXX" << endl;

}

countEvents::~countEvents()
{
  cout <<" DTOR" << endl;
}

void countEvents::beginJob()
{    
  cout << "HERE countEvents::beginJob()" << endl;

  tevCount = new TNtupleD("tevCount","event count","evCount1:evCount2");
}

void countEvents::endJob()
{
  //make a new Root file
  TFile myRootFile( theConfig.getParameter<std::string>("outHist").c_str(), "RECREATE");

  tevCount->Write();

  myRootFile.Close();

  delete tevCount;

  cout << "HERE countEvents::endJob()" << endl;
}

void countEvents::analyze(
    const edm::Event& ev, const edm::EventSetup& es)
{
  std::cout << " -------------------------------- HERE countEvents::analyze "<< std::endl;

 
  double one = 1.0;
  tevCount->Fill(one,one);

  cout <<"*** Analyze event: " << ev.id() <<" analysed event count:" << ++theEventCount << endl;

}

DEFINE_FWK_MODULE(countEvents);